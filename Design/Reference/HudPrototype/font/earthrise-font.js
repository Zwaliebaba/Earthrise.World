export function allGlyphs() {
  return Object.keys(G).map(ch => ({ ch, rows: G[ch], icon: false })).concat(Object.keys(IC).map(ch => ({ ch, rows: IC[ch].rows, icon: true, name: IC[ch].name })));
}
export function widthOf(rows) { return Math.max(0, ...rows.map(r => r.length)); }

export function buildFont(ot) {
  const rectPath = (rows, icon) => {
    const p = new ot.Path();
    rows.forEach((r, ri) => {
      let x = 0;
      while (x < r.length) {
        if (r[x] !== '#') { x++; continue; }
        let x1 = x; while (x1 < r.length && r[x1] === '#') x1++;
        const top = ((icon ? 8 : 7) - ri) * U, bot = top - U;
        p.moveTo(x * U, bot); p.lineTo(x1 * U, bot); p.lineTo(x1 * U, top); p.lineTo(x * U, top); p.close();
        x = x1;
      }
    });
    return p;
  };
  const glyphs = [new ot.Glyph({ name: '.notdef', unicode: 0, advanceWidth: 600, path: rectPath(['#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####'], false) })];
  allGlyphs().forEach(g => {
    const cp = g.ch.codePointAt(0);
    glyphs.push(new ot.Glyph({ name: 'uni' + cp.toString(16).toUpperCase().padStart(4, '0'), unicode: cp, advanceWidth: (widthOf(g.rows) + 1) * U, path: rectPath(g.rows, g.icon) }));
  });
  const font = new ot.Font({ familyName: NAME, styleName: 'Regular', unitsPerEm: 1000, ascender: 800, descender: -200, glyphs });
  return font.toArrayBuffer();
}

// A packed atlas for the engine's text renderer (MvpPlan: "bitmap font … baked into an atlas by a tool").
export function buildAtlas(doc, scale = 1) {
  const list = allGlyphs(), cols = 16, cell = 10, rowsN = Math.ceil(list.length / cols);
  const c = doc.createElement('canvas'); c.width = cols * cell * scale; c.height = rowsN * cell * scale;
  const g = c.getContext('2d'); g.fillStyle = '#ffffff';
  const map = { name: NAME, cell, scale, baselineRow: 7, glyphs: [] };
  list.forEach((gl, i) => {
    const cx = (i % cols) * cell, cy = Math.floor(i / cols) * cell, oy = gl.icon ? 0 : 1;
    gl.rows.forEach((r, ri) => { for (let x = 0; x < r.length; x++) if (r[x] === '#') g.fillRect((cx + x) * scale, (cy + oy + ri) * scale, scale, scale); });
    map.glyphs.push({ char: gl.ch, code: gl.ch.codePointAt(0), icon: gl.icon, name: gl.name || null, x: cx, y: cy, w: widthOf(gl.rows), h: gl.icon ? 9 : 9, top: oy, advance: widthOf(gl.rows) + 1, rows: gl.rows });
  });
  return { canvas: c, map };
}
